import { CATALOG } from "./items";
import { GOLD_PER_ROUND, START_GOLD, START_LIVES, WINS_TO_VICTORY } from "./run";
import { BACKPACK_SIZE, SHOP_SIZE } from "./shop";
import type { Backpack, GameState, RunState, SaveData, ShopOffers } from "./types";

// [req-6.2]: Define the currently supported save format version.
export const SAVE_VERSION = 1;

// [req-6.2]: Wrap the current game and submission information
// in a versioned save object.
export function createSaveData(
  game: GameState,
  submittedRunId: string | null = null,
  submissionName = "",
): SaveData {
  return {
    version: SAVE_VERSION,
    game,
    submittedRunId,
    submissionName,
  };
}

// [req-6.2]: Convert the complete save object into a JSON string
// so it can later be stored in localStorage.
export function serializeSave(save: SaveData): string {
  return JSON.stringify(save);
}

// [req-6.2]: Parse saved JSON without assuming that its contents
// are valid. Malformed JSON returns null instead of crashing.
export function parseSave(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

// [req-6.3]: Ensure unknown data is an object before
// accessing its properties.
function isRecord(
  value: unknown
): value is Record<string, unknown> {
  return (
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value)
  );
}

// [req-6.3]: Validate integer values and their allowed range
// to reject impossible numeric game states.
function isIntegerInRange(
  value: unknown,
  min: number,
  max: number
): value is number {
  return (
    typeof value === "number" &&
    Number.isSafeInteger(value) &&
    value >= min &&
    value <= max
  );
}

// [req-6.3]: Reject saved item IDs that do not exist
// in the current item catalog.
function isValidItemId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    CATALOG.some((item) => item.id === value)
  );
}

// [req-6.3]: Ensure the saved run identity matches
// the UUID v4 format generated by newRun().
function isValidRunId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)
  );
}

// [req-6.3]: Ensure the shop has the correct size and
// contains only known item IDs or empty offers.
function isValidShop(value: unknown): value is ShopOffers {
  return (
    Array.isArray(value) &&
    value.length === SHOP_SIZE &&
    [...value].every(
      (offer) => offer === null || isValidItemId(offer)
    )
  );
}

// [req-6.3]: Validate backpack size, item IDs and unique
// instance IDs to prevent invalid or duplicated items.
function isValidBackpack(
  value: unknown,
  nextUid: number
): value is Backpack {

  // Reject invalid backpack structures.
  if (!Array.isArray(value)) return false;
  if (value.length !== BACKPACK_SIZE) return false;

  // Remember all item UIDs that have already been checked.
  const seenUids = new Set<string>();

  for (const slot of value) {

    // Empty slots are valid.
    if (slot === null) continue;

    // An occupied slot must contain an object.
    if (!isRecord(slot)) return false;

    // The item must exist in the catalog.
    if (!isValidItemId(slot.itemId)) return false;

    // The UID must follow the format generated by buyItem().
    if (
      typeof slot.uid !== "string" ||
      !/^item-[1-9]\d*$/.test(slot.uid)
    ) return false;

    // Extract the numeric part of the UID.
    const uidNumber = Number(slot.uid.slice(5));

    // Existing UIDs must be smaller than the next available UID.
    if (!isIntegerInRange(uidNumber, 1, nextUid - 1)) {
      return false;
    }

    // Reject duplicate item instances.
    if (seenUids.has(slot.uid)) return false;

    // Remember this UID for the remaining slots.
    seenUids.add(slot.uid);
  }

  return true;
}

// [req-6.3]: Ensure that the round number matches
// the number of wins and lost lives.
function isValidRunProgress(
  round: number,
  wins: number,
  lives: number
): boolean {

  // A run cannot end in victory and defeat at the same time.
  if (wins === WINS_TO_VICTORY && lives === 0) {
    return false;
  }

  const losses = START_LIVES - lives;
  const completedBattles = wins + losses;

  const finished =
    wins === WINS_TO_VICTORY || lives === 0;

  // Finished runs do not advance to another round.
  if (finished) {
    return round === completedBattles;
  }

  // Active runs continue with the next round.
  return round === completedBattles + 1;
}

// [req-6.3]: Validate all persisted run values before
// allowing saved data to be used as a RunState.
export function isValidRunState(
  value: unknown
): value is RunState {

  // Ensure that the saved run is an object.
  if (!isRecord(value)) return false;

  // Validate the persistent run identity.
  if (!isValidRunId(value.runId)) return false;

  // A run lasts at most seven rounds.
  const maxRounds = WINS_TO_VICTORY + START_LIVES - 1;

  if (!isIntegerInRange(value.round, 1, maxRounds)) {
    return false;
  }

  // Gold cannot exceed the total gold earned in this run.
  const maxGold =
    START_GOLD + (value.round - 1) * GOLD_PER_ROUND;

  if (!isIntegerInRange(value.gold, 0, maxGold)) {
    return false;
  }

  // Validate lives and wins.
  if (!isIntegerInRange(value.lives, 0, START_LIVES)) {
    return false;
  }

  if (!isIntegerInRange(value.wins, 0, WINS_TO_VICTORY)) {
    return false;
  }

  // The shop seed must be an unsigned 32-bit integer.
  if (!isIntegerInRange(value.seed, 0, 2 ** 32 - 1)) {
    return false;
  }

  // Validate the counter used for new item instances.
  if (!isIntegerInRange(
    value.nextUid,
    1,
    Number.MAX_SAFE_INTEGER
  )) {
    return false;
  }

  // Validate the saved shop and backpack.
  if (!isValidShop(value.shop)) return false;

  if (!isValidBackpack(value.backpack, value.nextUid)) {
    return false;
  }

  // Ensure that the run's progress is internally consistent.
  return isValidRunProgress(
    value.round,
    value.wins,
    value.lives
  );
}

// [req-6.3]: Reject unsupported save versions and invalid
// outer structures before validating the full game state.
export function hasValidSaveStructure(
  value: unknown
): boolean {

  // A save must be an object.
  if (!isRecord(value)) return false;

  // Only the currently supported save version is accepted.
  if (value.version !== SAVE_VERSION) return false;

  // The saved game must be an object.
  if (!isRecord(value.game)) return false;

  // The saved run must be valid.
  if (!isValidRunState(value.game.run)) return false;

  // A submitted run ID must belong to the saved run.
  if (
    value.submittedRunId !== null &&
    value.submittedRunId !== value.game.run.runId
  ) {
    return false;
  }

  // The entered submission name must be a string.
  if (typeof value.submissionName !== "string") {
    return false;
  }

  return true;
}
