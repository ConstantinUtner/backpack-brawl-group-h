import { buildOpponentFighter, buildPlayerFighter, simulateBattle } from "./battle";
import { isReplayDone } from "./game";
import { CATALOG } from "./items";
import { GOLD_PER_ROUND, START_GOLD, START_LIVES, WINS_TO_VICTORY, runOutcome } from "./run";
import { BACKPACK_SIZE, SHOP_SIZE } from "./shop";
import type { Backpack, BattleReplay, GameState, Opponent, RunState, SaveData, ShopOffers } from "./types";

// [req-6.2]: Define the currently supported save format version.
export const SAVE_VERSION = 1;

// [req-6.6]: Use a consistent key to store and retrieve the game save.
export const SAVE_KEY = "backpack-brawl-save";

// [req-6.2]: Wrap the current game and submission information
// in a versioned save object.
export function createSaveData(
  game: GameState,
  submittedRunId: string | null = null,
  submissionName = "",
): SaveData {
  return {
    version: SAVE_VERSION,
    game,
    submittedRunId,
    submissionName,
  };
}

// [req-6.2]: Convert the complete save object into a JSON string
// so it can later be stored in localStorage.
export function serializeSave(save: SaveData): string {
  return JSON.stringify(save);
}

// [req-6.2]: Parse saved JSON without assuming that its contents
// are valid. Malformed JSON returns null instead of crashing.
export function parseSave(raw: string): unknown {
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

// [req-6.3]: Ensure unknown data is an object before
// accessing its properties.
function isRecord(
  value: unknown
): value is Record<string, unknown> {
  return (
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value)
  );
}

// [req-6.3]: Validate integer values and their allowed range
// to reject impossible numeric game states.
function isIntegerInRange(
  value: unknown,
  min: number,
  max: number
): value is number {
  return (
    typeof value === "number" &&
    Number.isSafeInteger(value) &&
    value >= min &&
    value <= max
  );
}

// [req-6.3]: Reject saved item IDs that do not exist
// in the current item catalog.
function isValidItemId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    CATALOG.some((item) => item.id === value)
  );
}

// [req-6.3]: Ensure the saved run identity matches
// the UUID v4 format generated by newRun().
function isValidRunId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)
  );
}

// [req-6.3]: Ensure the shop has the correct size and
// contains only known item IDs or empty offers.
function isValidShop(value: unknown): value is ShopOffers {
  return (
    Array.isArray(value) &&
    value.length === SHOP_SIZE &&
    [...value].every(
      (offer) => offer === null || isValidItemId(offer)
    )
  );
}

// [req-6.3]: Validate backpack size, item IDs and unique
// instance IDs to prevent invalid or duplicated items.
function isValidBackpack(
  value: unknown,
  nextUid: number
): value is Backpack {

  // Reject invalid backpack structures.
  if (!Array.isArray(value)) return false;
  if (value.length !== BACKPACK_SIZE) return false;

  // Remember all item UIDs that have already been checked.
  const seenUids = new Set<string>();

  for (const slot of value) {

    // Empty slots are valid.
    if (slot === null) continue;

    // An occupied slot must contain an object.
    if (!isRecord(slot)) return false;

    // The item must exist in the catalog.
    if (!isValidItemId(slot.itemId)) return false;

    // The UID must follow the format generated by buyItem().
    if (
      typeof slot.uid !== "string" ||
      !/^item-[1-9]\d*$/.test(slot.uid)
    ) return false;

    // Extract the numeric part of the UID.
    const uidNumber = Number(slot.uid.slice(5));

    // Existing UIDs must be smaller than the next available UID.
    if (!isIntegerInRange(uidNumber, 1, nextUid - 1)) {
      return false;
    }

    // Reject duplicate item instances.
    if (seenUids.has(slot.uid)) return false;

    // Remember this UID for the remaining slots.
    seenUids.add(slot.uid);
  }

  return true;
}

// [req-6.3]: Ensure that the round number matches
// the number of wins and lost lives.
function isValidRunProgress(
  round: number,
  wins: number,
  lives: number
): boolean {

  // A run cannot end in victory and defeat at the same time.
  if (wins === WINS_TO_VICTORY && lives === 0) {
    return false;
  }

  const losses = START_LIVES - lives;
  const completedBattles = wins + losses;

  const finished =
    wins === WINS_TO_VICTORY || lives === 0;

  // Finished runs do not advance to another round.
  if (finished) {
    return round === completedBattles;
  }

  // Active runs continue with the next round.
  return round === completedBattles + 1;
}

// [req-6.3]: Validate all persisted run values before
// allowing saved data to be used as a RunState.
export function isValidRunState(
  value: unknown
): value is RunState {

  // Ensure that the saved run is an object.
  if (!isRecord(value)) return false;

  // Validate the persistent run identity.
  if (!isValidRunId(value.runId)) return false;

  // A run lasts at most seven rounds.
  const maxRounds = WINS_TO_VICTORY + START_LIVES - 1;

  if (!isIntegerInRange(value.round, 1, maxRounds)) {
    return false;
  }

  // Gold cannot exceed the total gold earned in this run.
  const maxGold =
    START_GOLD + (value.round - 1) * GOLD_PER_ROUND;

  if (!isIntegerInRange(value.gold, 0, maxGold)) {
    return false;
  }

  // Validate lives and wins.
  if (!isIntegerInRange(value.lives, 0, START_LIVES)) {
    return false;
  }

  if (!isIntegerInRange(value.wins, 0, WINS_TO_VICTORY)) {
    return false;
  }

  // The shop seed must be an unsigned 32-bit integer.
  if (!isIntegerInRange(value.seed, 0, 2 ** 32 - 1)) {
    return false;
  }

  // Validate the counter used for new item instances.
  if (!isIntegerInRange(
    value.nextUid,
    1,
    Number.MAX_SAFE_INTEGER
  )) {
    return false;
  }

  // Validate the saved shop and backpack.
  if (!isValidShop(value.shop)) return false;

  if (!isValidBackpack(value.backpack, value.nextUid)) {
    return false;
  }

  // Ensure that the run's progress is internally consistent.
  return isValidRunProgress(
    value.round,
    value.wins,
    value.lives
  );
}

// [req-6.3]: Reject unsupported save versions and invalid
// outer structures before validating the full game state.
export function hasValidSaveStructure(
  value: unknown
): boolean {

  // A save must be an object.
  if (!isRecord(value)) return false;

  // Only the currently supported save version is accepted.
  if (value.version !== SAVE_VERSION) return false;

  // The saved game must be an object.
  if (!isRecord(value.game)) return false;

  // The saved run must be valid.
  if (!isValidRunState(value.game.run)) return false;

  // A submitted run ID must belong to the saved run.
  if (
    value.submittedRunId !== null &&
    value.submittedRunId !== value.game.run.runId
  ) {
    return false;
  }

  // The entered submission name must be a string.
  if (typeof value.submissionName !== "string") {
    return false;
  }

  return true;
}

// [req-6.4]: Validate the saved opponent before using it
// to check the battle replay.
function isValidOpponent(value: unknown): value is Opponent {

  if (!isRecord(value)) return false;

  // Validate the opponent's identity and display information.
  if (typeof value.id !== "string" || value.id.length === 0) {
    return false;
  }

  if (typeof value.name !== "string") return false;
  if (typeof value.icon !== "string") return false;

  // The opponent must have positive health.
  if (!isIntegerInRange(value.hp, 1, Number.MAX_SAFE_INTEGER)) {
    return false;
  }

  // The opponent must belong to a possible round.
  const maxRounds = WINS_TO_VICTORY + START_LIVES - 1;

  if (!isIntegerInRange(value.round, 1, maxRounds)) {
    return false;
  }

  // The opponent can only carry known items.
  if (!Array.isArray(value.items)) return false;
  if (value.items.length > BACKPACK_SIZE) return false;

  return [...value.items].every(isValidItemId);
}

// [req-6.4]: Validate the complete replay against the existing
// deterministic battle simulation instead of duplicating combat rules.
function isValidBattleReplay(
  value: unknown,
  run: RunState
): value is BattleReplay {

  if (!isRecord(value)) return false;

  // Validate the opponent before rebuilding the fighters.
  if (!isValidOpponent(value.opponent)) return false;

  // A battle requires at least one player item.
  if (run.backpack.every((slot) => slot === null)) {
    return false;
  }

  // Rebuild the expected fighters using the existing game logic.
  const player = buildPlayerFighter(run.backpack);
  const enemy = buildOpponentFighter(value.opponent);

  try {
    // Reject inconsistent saved fighter data.
    if (JSON.stringify(value.player) !== JSON.stringify(player)) {
      return false;
    }

    if (JSON.stringify(value.enemy) !== JSON.stringify(enemy)) {
      return false;
    }

    // Calculate the expected result for validation only.
    const expectedResult = simulateBattle(player, enemy);

    // The saved winner, frames and events must match the expected result.
    if (JSON.stringify(value.result) !== JSON.stringify(expectedResult)) {
      return false;
    }

    // The replay must point to an existing frame.
    return isIntegerInRange(value.frame, 0, expectedResult.frames.length - 1);
  } catch {
    // [req-6.4]: Reject replay data that cannot be serialized as JSON.
    return false;
  }
}

// [req-6.4]: Ensure the saved replay belongs to the correct round
// and matches whether its result has already been applied.
function isValidBattleProgress(
  battle: BattleReplay,
  run: RunState
): boolean {

  const done = isReplayDone(battle);
  const outcome = runOutcome(run);

  // An unfinished replay must belong to the current active round.
  if (!done) {
    return outcome === null &&
      battle.opponent.round === run.round;
  }

  // A scored victory requires at least one recorded win.
  if (battle.result.winner === "player" && run.wins === 0) {
    return false;
  }

  // A scored defeat requires at least one lost life.
  if (
    battle.result.winner === "opponent" &&
    run.lives === START_LIVES
  ) {
    return false;
  }

  // If the battle ended the run, the round did not advance.
  if (outcome !== null) {
    const expectedWinner =
      outcome === "victory" ? "player" : "opponent";

    return (
      battle.opponent.round === run.round &&
      battle.result.winner === expectedWinner
    );
  }

  // A completed battle in an active run belongs to the previous round.
  return battle.opponent.round === run.round - 1;
}

// [req-6.4]: Validate the game phase and ensure that
// search, battle and run state are consistent.
export function isValidGameState(
  value: unknown
): value is GameState {

  if (!isRecord(value)) return false;
  if (!isValidRunState(value.run)) return false;

  // Search errors must be strings or null.
  if (value.error !== null && typeof value.error !== "string") {
    return false;
  }

  const outcome = runOutcome(value.run);

  switch (value.phase) {

    case "shop":
      // Shopping requires an active run without a search or battle.
      return (
        outcome === null &&
        value.activeSearch === null &&
        value.battle === null
      );

    case "searching":
      // A search requires an active run and no existing battle.
      if (outcome !== null || value.battle !== null) {
        return false;
      }

      // Matchmaking requires at least one backpack item.
      if (value.run.backpack.every((slot) => slot === null)) {
        return false;
      }

      // The active search must belong to the current round.
      return (
        isRecord(value.activeSearch) &&
        typeof value.activeSearch.searchId === "string" &&
        value.activeSearch.searchId.length > 0 &&
        value.activeSearch.round === value.run.round &&
        value.error === null
      );

    case "battle":
      // A battle cannot have an active search.
      if (value.activeSearch !== null || value.error !== null) {
        return false;
      }

      // Validate the replay itself and its relationship to the run.
      return (
        isValidBattleReplay(value.battle, value.run) &&
        isValidBattleProgress(value.battle, value.run)
      );

    case "finished":
      // A finished game must have a completed run without a search or battle.
      return (
        outcome !== null &&
        value.activeSearch === null &&
        value.battle === null &&
        value.error === null
      );

    default:
      // Reject unknown or missing game phases.
      return false;
  }
}

// [req-6.4]: Accept a save only when its format,
// complete game state and submission status are valid.
export function isValidSaveData(
  value: unknown
): value is SaveData {

  // Validate the save format and its basic metadata.
  if (!hasValidSaveStructure(value)) return false;

  // Narrow the unknown value before accessing its properties.
  if (!isRecord(value)) return false;

  // Validate the complete game, including phase and replay.
  if (!isValidGameState(value.game)) return false;

  // Hall of Fame submissions are only possible on the result page.
  if (value.submittedRunId !== null) {
    if (value.game.phase !== "finished") return false;

    // A successfully submitted run requires a valid player name.
    if (typeof value.submissionName !== "string") {
      return false;
    }

    const name = value.submissionName.trim();

    if (name.length === 0 || name.length > 30) {
      return false;
    }
  }

  return true;
}

// [req-6.5]: Cancel interrupted matchmaking on refresh.
// All other valid game states can be restored unchanged.
export function restoreGame(game: GameState): GameState {
  if (game.phase === "searching") {
    return {
      ...game,
      phase: "shop",
      activeSearch: null,
      error: null,
    };
  }

  return game;
}

// [req-6.5]: Parse and validate saved data before applying
// the refresh policy. Invalid saves return null.
export function restoreSave(raw: string): SaveData | null {
  const parsed = parseSave(raw);

  if (!isValidSaveData(parsed)) {
    return null;
  }

  return {
    ...parsed,
    game: restoreGame(parsed.game),
  };
}

// [req-6.6]: Serialize and persist the complete save.
// Handle storage failures without crashing the game.
export function saveGame(save: SaveData): boolean {
  try {
    localStorage.setItem(SAVE_KEY, serializeSave(save));
    return true;
  } catch {
    return false;
  }
}

// [req-6.6]: Remove the stored save without affecting
// other localStorage entries.
export function clearSave(): void {
  try {
    localStorage.removeItem(SAVE_KEY);
  } catch {
    // Storage may be unavailable.
  }
}

// [req-6.6]: Load and restore the saved game.
// Discard invalid saves and return null if recovery fails.
export function loadGame(): SaveData | null {
  try {
    const raw = localStorage.getItem(SAVE_KEY);

    if (raw === null) return null;

    const restored = restoreSave(raw);

    if (restored === null) {
      clearSave();
    }

    return restored;
  } catch {
    return null;
  }
}
